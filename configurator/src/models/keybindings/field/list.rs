pub fn keybinding_fields() -> Vec<KeybindingField> {
    let mut fields = PREFERRED_ORDER.to_vec();
    for &field in KeybindingField::all() {
        if !fields.contains(&field) {
            fields.push(field);
        }
    }
    fields
}
